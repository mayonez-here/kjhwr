#!/usr/bin/env python
"""Generate a SYNTHETIC snapshot for development and tests only.

    python scripts/make_synthetic.py

The output is flagged meta.source = "synthetic" and the UI shows a warning banner.
It is NOT real Elexon data - run scripts/fetch_data.py to replace it.
"""
import json
import math
import random
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UTC = timezone.utc
iso = lambda d: d.strftime("%Y-%m-%dT%H:%M:%SZ")  # noqa: E731


def main():
    rng = random.Random(42)
    start = datetime(2026, 1, 1, tzinfo=UTC)
    end = datetime(2026, 2, 2, tzinfo=UTC)

    # AR(1) wind level between ~500 and ~19000 MW
    actual, level, t = {}, 8000.0, start
    while t < end:
        level = 0.985 * level + 0.015 * 8000 + rng.gauss(0, 330)
        level = min(max(level, 400), 19500)
        actual[t] = level
        t += timedelta(minutes=30)

    forecasts = []
    pub = datetime(2025, 12, 31, tzinfo=UTC)
    while pub < datetime(2026, 2, 1, tzinfo=UTC):
        # one forecast run every 3 h, hourly values out to 48 h
        for h in range(1, 49):
            target = pub + timedelta(hours=h)
            if target not in actual:
                continue
            sigma = 400 + 90 * h                     # error grows with lead time
            val = actual[target] + rng.gauss(150, sigma)  # slight over-forecast bias
            forecasts.append([iso(target), iso(pub), round(max(val, 0), 1)])
        pub += timedelta(hours=3)

    snap = {
        "meta": {"source": "synthetic", "fetched_at": iso(datetime.now(UTC)),
                 "note": "Generated by scripts/make_synthetic.py - NOT real data"},
        "actuals": [[iso(t), round(v, 1)] for t, v in sorted(actual.items())],
        "forecasts": forecasts,
    }
    out = ROOT / "data" / "snapshot.json"
    out.write_text(json.dumps(snap, separators=(",", ":")))
    print(f"Wrote {out}: {len(snap['actuals'])} actuals, {len(forecasts)} forecasts")


if __name__ == "__main__":
    main()
